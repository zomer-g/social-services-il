#!/usr/bin/env node
/**
 * Regenerates packages/api/src/data/localities.ts from the CBS localities file.
 *
 * The dashboard breaks the corpus down by district and puts a town's services
 * next to its population. Neither is in the corpus: a card knows its city by
 * name and nothing else. The CBS publishes both, per locality, once a year, on
 * data.gov.il — so this pulls that file and keeps the five columns that matter.
 *
 * Checked in rather than fetched at boot: the file changes once a year, and the
 * API should not depend on data.gov.il being up to start.
 *
 *   node scripts/build-localities.mjs            # the 2023 file
 *   node scripts/build-localities.mjs <resource> # another year's resource id
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const RESOURCE = process.argv[2] ?? 'd47a54ff-87f0-44b3-b33a-f284c0c38e5a';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'api', 'src', 'data', 'localities.ts');

const url = `https://data.gov.il/api/3/action/datastore_search?resource_id=${RESOURCE}&limit=5000`;
const res = await fetch(url, { headers: { 'user-agent': 'social-services-il/build-localities' } });
if (!res.ok) throw new Error(`data.gov.il answered ${res.status}`);
const { result } = await res.json();

/** The population column is named for its year, and the year changes. */
const popKey = Object.keys(result.records[0]).find((k) => k.startsWith('סך הכל אוכלוסייה'));
if (!popKey) throw new Error('no population column in this resource');

// CBS "דת יישוב": 1 Jewish, 2 Arab (non-Bedouin), 3 Bedouin, 4 mixed.
const SECTORS = { 1: 'jewish', 2: 'arab', 3: 'bedouin', 4: 'mixed' };

const rows = result.records
  .filter((r) => r['שם יישוב'] && Number(r[popKey]) > 0)
  .map((r) => [
    String(r['שם יישוב']).trim(),
    String(r['שם מחוז'] ?? '').trim(),
    String(r['שם נפה'] ?? '').trim(),
    Number(r[popKey]),
    SECTORS[r['דת יישוב']] ?? null,
  ])
  .sort((a, b) => b[3] - a[3]);

const body = `/**
 * CBS localities: name, district, sub-district, population, sector.
 *
 * Generated by scripts/build-localities.mjs from data.gov.il resource
 * ${RESOURCE} (${popKey}). Do not edit by hand.
 */

export type Sector = 'jewish' | 'arab' | 'bedouin' | 'mixed';
export type Locality = readonly [name: string, district: string, subdistrict: string, population: number, sector: Sector | null];

export const LOCALITIES_SOURCE = ${JSON.stringify({ resource: RESOURCE, column: popKey, url: 'https://data.gov.il/he/datasets/lamas/localities-in-israel' })};

export const LOCALITIES: readonly Locality[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;

writeFileSync(OUT, body);
console.log(`wrote ${rows.length} localities to ${OUT}`);
